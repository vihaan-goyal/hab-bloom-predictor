"""
make_demo_season.py -- store one real season on the board for the `demo` command
--------------------------------------------------------------------------------
Writes demo_season.h: the daily rows of one Narragansett station-season (default B3, 2023), exactly
as the fork's training table has them. `demo` on the board replays them through the same code path
as real days (features, model, treatment loop, bulletins), so nothing in the demo is invented.

    python make_demo_season.py                       B3, 2023-05-01..2023-10-19, 21 warm-up days before
    python make_demo_season.py --station B6 --start 2022-05-01 --end 2022-10-15

The warm-up rows fill the model's 21-day window before the first shown day; the board replays them
without bulletins.
"""
import argparse
import os

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_FORK = os.path.abspath(os.path.join(HERE, "..", "..", "..", "hab-bloom-predictor-narragansett"))
WARMUP = 21


def cnum(v):
    return "NAN" if pd.isna(v) else f"{v:.6g}f"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--station", default="B3")
    ap.add_argument("--start", default="2023-05-01")
    ap.add_argument("--end", default="2023-10-19")
    ap.add_argument("--fork", default=DEFAULT_FORK)
    a = ap.parse_args()

    df = pd.read_csv(os.path.join(a.fork, "data", "narragansett_daily_features.csv"), parse_dates=["date"])
    st = df[(df.station == a.station) & df.chl.notna()].sort_values("date").reset_index(drop=True)
    i0 = int(st["date"].searchsorted(pd.Timestamp(a.start)))
    i1 = int(st["date"].searchsorted(pd.Timestamp(a.end), side="right"))
    rows = st.iloc[max(0, i0 - WARMUP):i1]
    warm = i0 - max(0, i0 - WARMUP)
    if len(rows) - warm < 10:
        raise SystemExit(f"only {len(rows) - warm} days for {a.station} in {a.start}..{a.end}")

    out = [
        "// demo_season.h -- GENERATED by make_demo_season.py; do not edit.",
        f"// Real daily rows of Narragansett station {a.station}, {rows.date.iloc[warm]:%Y-%m-%d}..{rows.date.iloc[-1]:%Y-%m-%d}"
        f" ({len(rows) - warm} days), after {warm} warm-up rows.",
        "// Source: the fork's data/narragansett_daily_features.csv (RIDEM fixed-site sondes).",
        "#ifndef DEMO_SEASON_H",
        "#define DEMO_SEASON_H",
        "",
        f'#define DEMO_STATION "{a.station}"',
        f"#define DEMO_N {len(rows)}",
        f"#define DEMO_WARMUP {warm}",
        "",
        "// {yyyymmdd, chl, temp, sal, do, chl_climatology}: the field order of DayRec (features.h)",
        "static const DayRec DEMO_ROWS[DEMO_N] PROGMEM = {",
    ]
    for _, r in rows.iterrows():
        out.append(f"  {{{r.date:%Y%m%d}, {cnum(r.chl)}, {cnum(r.temp)}, {cnum(r.sal)}, {cnum(r['do'])}, {cnum(r.chl_climatology)}}},")
    out += ["};", "", "#endif", ""]
    path = os.path.join(HERE, "demo_season.h")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(out))
    print(f"wrote {path}: {len(rows)} rows ({warm} warm-up), {a.station} {rows.date.iloc[0]:%Y-%m-%d}..{rows.date.iloc[-1]:%Y-%m-%d}, "
          f"{int((rows.chl.iloc[warm:] > 10).sum())} days with chl > 10")


if __name__ == "__main__":
    main()
